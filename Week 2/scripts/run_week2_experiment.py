def load_selected_items() -> list[dict]:
    if not SELECTED_ITEMS_JSONL.exists():
        print(
            f"Missing {SELECTED_ITEMS_JSONL}; run "
            f"'Week 2/scripts/select_items.py' first.",
            file=sys.stderr,
        )
        sys.exit(1)
    rows = [json.loads(line) for line in SELECTED_ITEMS_JSONL.read_text().splitlines() if line]
    # Preserve base-item order as chosen by select_items.py, then a fixed
    # within-item condition order.
    order_key = {}
    cond_order = {("ambig", "neg"): 0, ("ambig", "nonneg"): 1, ("disambig", "neg"): 2, ("disambig", "nonneg"): 3}
    for r in rows:
        if r["base_item_id"] not in order_key:
            order_key[r["base_item_id"]] = len(order_key)
    rows.sort(key=lambda r: (order_key[r["base_item_id"]], cond_order[(r["context_condition"], r["question_polarity"])]))
    return rows


def base_items_in_order(rows: list[dict]) -> list[str]:
    seen: list[str] = []
    for r in rows:
        if r["base_item_id"] not in seen:
            seen.append(r["base_item_id"])
    return seen


