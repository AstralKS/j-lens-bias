#!/usr/bin/env python3
"""Week 2 Jacobian Lens BBQ bias experiment runner (Cohere Labs J-Lens Bias).

Standalone, sequential, checkpoint/resume-capable driver so the expensive
model computation does not depend on a live Claude/notebook session. Uses
ONLY the released, pre-fitted Qwen3.5-0.8B Jacobian lens via the official
`jlens` package (read-only dependency on ~/Desktop/JLens-project/
jacobian-lens). Never calls jlens.fit()/train()/refit().

Research question (Week 2 README): does the J-Lens workspace-band readout
surface stereotype-congruent tokens more strongly than counter-stereotype
tokens on BBQ items, including in ambiguous contexts, and does the effect
track question polarity?

Design summary (see Week 2/data/selection_manifest.json for the full,
per-item audit trail):
  - Category: BBQ "Age" (official nyu-mll/BBQ data/Age.jsonl).
  - 10 matched base items x 4 conditions (ambig/disambig x neg/nonneg) = 40
    prompts, staged 1 (sanity) -> 5 -> 8 -> 10 with a memory gate at each
    boundary.
  - Prompt format: "{context}\n{question}\n(a) {ans0}\n(b) {ans1}\n
    (c) {ans2}\nAnswer:" (verified by direct tokenization: the last token is
    the ':' of 'Answer:', i.e. the position immediately before the model
    would generate).
  - Source position: the single last token position (answer-generation
    position), not the whole prompt -- verified per item, never assumed.
  - Layers: the lens's full fitted source_layers trajectory, plus the
    model's own final layer as an extra "model_output" row (J = identity),
    matching jlens.vis.compute_slice's own semantics.
  - Top-K = 20, using jlens.vis._meaningful_token_mask (word-like tokens
    only) and jlens.vis._ranks_of (full-vocab rank, 0 = top) -- the exact
    helpers the official slice-vis page uses, not a reimplementation.
  - Multi-token targets: stereotype/counter target text is tokenized as
    " " + target_text (leading space, matching how a continuation word is
    actually generated by a BPE tokenizer), constituent tokens filtered to
    "meaningful" ones, and group rank = min(rank) across those constituents
    (documented "best-constituent" rule; lower numerical rank = stronger).
  - rank_gap = counter_rank - stereotype_rank (positive => stereotype target
    ranks stronger/lower-numbered).
"""

