def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sanity-only", action="store_true", help="Process exactly one prompt and exit.")
    parser.add_argument(
        "--max-base-items", type=int, default=HARD_CAP_BASE_ITEMS, help="Hard cap on base items this run."
    )
    args = parser.parse_args()
    max_base_items = min(args.max_base_items, HARD_CAP_BASE_ITEMS)

    check_no_other_qwen_process()
    acquire_lock()
    try:
        run(args.sanity_only, max_base_items)
    finally:
        release_lock()


def run(sanity_only: bool, max_base_items: int) -> None:
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    CKPT_DIR.mkdir(parents=True, exist_ok=True)

    pre_load = check_memory()
    log_memory("pre_model_load", pre_load)
    if not memory_is_safe(pre_load, pre_load)[0]:
        print("MEMORY SAFETY STOP: unsafe BEFORE model load; aborting without loading model.")
        write_recovery_state({"needs_finalization": True, "stopped_at": "pre_model_load", "completed_prompts": 0})
        sys.exit(2)

    all_rows = load_selected_items()
    base_order = base_items_in_order(all_rows)
    if sanity_only:
        target_base_items = base_order[:1]
        rows_scope = [r for r in all_rows if r["base_item_id"] == target_base_items[0]][:1]
    else:
        target_base_items = base_order[:max_base_items]
        rows_scope = [r for r in all_rows if r["base_item_id"] in target_base_items]

    pending = [r for r in rows_scope if not is_already_done(r)]
    if not pending:
        print("All requested prompts already have valid checkpoints. Nothing to do.")
        n_rows = combine_checkpoints()
        print(f"{n_rows} total rows in {RAW_CSV}.")
        return

    model, tokenizer, lens = load_model_and_lens()
    import torch

    post_load = check_memory(torch)
    log_memory("post_model_load", post_load)
    ok, reason = memory_is_safe(post_load, pre_load)
    if not ok:
        print(f"MEMORY SAFETY STOP after model load: {reason}")
        write_recovery_state({"needs_finalization": True, "stopped_at": "post_model_load", "completed_prompts": 0})
        sys.exit(2)

    baseline = post_load  # MPS drift measured relative to right after load
    done_base_items: set[str] = set()
    n_completed_this_run = 0
    stopped_reason = None

    for row in pending:
        ckpt = checkpoint_path(row)
        tag = f"{row['base_item_id']}/{row['context_condition']}/{row['question_polarity']}"
        print(f"--- {tag} ---", file=sys.stderr)
        t0 = time.time()
        try:
            out_rows = process_row(model, tokenizer, lens, row)
        except Exception as exc:  # noqa: BLE001
            print(f"ERROR processing {tag}: {exc!r}; stopping (not marking complete).", file=sys.stderr)
            stopped_reason = f"exception on {tag}: {exc!r}"
            break
        write_checkpoint_atomic(ckpt, out_rows)
        assert checkpoint_is_valid(ckpt), f"checkpoint write verification failed: {ckpt}"
        mark_completed(row, ckpt)
        n_completed_this_run += 1
        dt = time.time() - t0
        print(f"    {len(out_rows)} rows -> {ckpt.name} in {dt:.1f}s", file=sys.stderr)

        del out_rows
        gc.collect()
        if torch.backends.mps.is_available():
            torch.mps.empty_cache()

        snap = check_memory(torch)
        log_memory(f"after_{ckpt.stem}", snap)
        ok, reason = memory_is_safe(snap, baseline)
        if not ok:
            print(f"MEMORY SAFETY STOP: {reason}")
            stopped_reason = reason
            break

        done_base_items.add(row["base_item_id"])
        n_done_base = len([b for b in target_base_items if b in done_base_items])
        # Only gate at a boundary once all 4 conditions of that base item are done.
        rows_for_base = [r for r in rows_scope if r["base_item_id"] == row["base_item_id"]]
        base_fully_done = all(is_already_done(r) for r in rows_for_base)
        if base_fully_done and n_done_base in STAGE_BOUNDARIES:
            print(f"Stage boundary reached: {n_done_base} base item(s) complete. Re-checking memory ...")
            ok, reason = memory_is_safe(snap, pre_load)
            if not ok:
                print(f"MEMORY SAFETY STOP at stage boundary {n_done_base}: {reason}")
                stopped_reason = reason
                break

    n_rows = combine_checkpoints()
    n_manifest = len(json.loads(COMPLETED_JSON.read_text())) if COMPLETED_JSON.exists() else 0
    print(f"Done. {n_manifest} prompt(s) total completed; {n_rows} total rows in {RAW_CSV}.")

    remaining = [r for r in all_rows if not is_already_done(r)]
    write_recovery_state(
        {
            "needs_finalization": stopped_reason is not None,
            "stopped_reason": stopped_reason,
            "completed_prompts": n_manifest,
            "remaining_prompts": len(remaining),
            "sanity_only": sanity_only,
            "max_base_items": max_base_items,
        }
    )
    if stopped_reason:
        print(f"Stopped early: {stopped_reason}. State saved to {RECOVERY_STATE}.")


if __name__ == "__main__":
    for _sig in (signal.SIGINT, signal.SIGTERM):
        signal.signal(_sig, lambda *_: (_ for _ in ()).throw(KeyboardInterrupt()))
    main()
