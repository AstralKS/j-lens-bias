def _pid_is_alive(pid: int) -> bool:
    try:
        os.kill(pid, 0)
    except OSError:
        return False
    return True


def acquire_lock() -> None:
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    if PID_FILE.exists():
        try:
            existing_pid = int(PID_FILE.read_text().strip())
        except ValueError:
            existing_pid = -1
        if existing_pid > 0 and _pid_is_alive(existing_pid):
            print(
                f"REFUSING TO START: another Week 2 runner appears active "
                f"(pid {existing_pid} in {PID_FILE}). Not launching a second "
                f"model process."
            )
            sys.exit(3)
        print(f"Stale lock file (pid {existing_pid} not alive); replacing.")
    PID_FILE.write_text(str(os.getpid()))


def release_lock() -> None:
    try:
        if PID_FILE.exists() and PID_FILE.read_text().strip() == str(os.getpid()):
            PID_FILE.unlink()
    except OSError:
        pass


def check_no_other_qwen_process() -> None:
    """Best-effort scan for another project-related Qwen/jlens process (not
    just our own PID-file lock) before touching MPS."""
    try:
        out = subprocess.run(["ps", "-eo", "pid,command"], capture_output=True, text=True).stdout
    except Exception:
        return
    my_pid = os.getpid()
    my_ppid = os.getppid()
    for line in out.splitlines():
        parts = line.strip().split(None, 1)
        if len(parts) != 2:
            continue
        pid_str, command = parts
        try:
            pid = int(pid_str)
        except ValueError:
            continue
        if pid in (my_pid, my_ppid):
            continue
        command_l = command.lower()
        # Only match an actual python interpreter invoking the runner script
        # as its argv, not a shell wrapper that merely contains the text
        # (e.g. the terminal harness's own `sh -c '...run_week2_experiment.py...'`).
        first_token = command.split()[0] if command.split() else ""
        is_python = Path(first_token).name.startswith("python")
        if is_python and "run_week2_experiment.py" in command_l and _pid_is_alive(pid):
            print(f"REFUSING TO START: found another runner process (pid {pid}): {command}")
            sys.exit(3)


