def checkpoint_path(row: dict) -> Path:
    name = f"{row['base_item_id']}__{row['context_condition']}__{row['question_polarity']}.csv"
    return CKPT_DIR / name


def checkpoint_is_valid(path: Path) -> bool:
    if not path.exists() or path.stat().st_size == 0:
        return False
    try:
        with open(path, newline="") as f:
            reader = csv.DictReader(f)
            if reader.fieldnames != CSV_FIELDS:
                return False
            return any(True for _ in reader)
    except Exception:
        return False


def write_checkpoint_atomic(path: Path, rows: list[dict]) -> None:
    tmp = path.with_suffix(".csv.tmp")
    with open(tmp, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_FIELDS)
        writer.writeheader()
        writer.writerows(rows)
        f.flush()
        os.fsync(f.fileno())
    tmp.replace(path)


def mark_completed(row: dict, ckpt: Path) -> None:
    completed = []
    if COMPLETED_JSON.exists():
        completed = json.loads(COMPLETED_JSON.read_text())
    key = (row["base_item_id"], row["context_condition"], row["question_polarity"])
    entry = {
        "category": row["category"],
        "base_item_id": row["base_item_id"],
        "example_id": row["example_id"],
        "context_condition": row["context_condition"],
        "question_polarity": row["question_polarity"],
        "checkpoint_path": str(ckpt),
    }
    completed = [
        c
        for c in completed
        if (c["base_item_id"], c["context_condition"], c["question_polarity"]) != key
    ]
    completed.append(entry)
    COMPLETED_JSON.write_text(json.dumps(completed, indent=2))


def is_already_done(row: dict) -> bool:
    ckpt = checkpoint_path(row)
    if not checkpoint_is_valid(ckpt):
        return False
    if not COMPLETED_JSON.exists():
        return False
    completed = json.loads(COMPLETED_JSON.read_text())
    key = (row["base_item_id"], row["context_condition"], row["question_polarity"])
    return any(
        (c["base_item_id"], c["context_condition"], c["question_polarity"]) == key
        for c in completed
    )


def combine_checkpoints() -> int:
    all_rows = []
    for ckpt in sorted(CKPT_DIR.glob("*.csv")):
        if ckpt.name.endswith(".tmp"):
            continue
        with open(ckpt, newline="") as f:
            reader = csv.DictReader(f)
            all_rows.extend(reader)
    if not all_rows:
        return 0
    with open(RAW_CSV, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_FIELDS)
        writer.writeheader()
        writer.writerows(all_rows)
    return len(all_rows)


